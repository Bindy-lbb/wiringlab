import type { Device, Kind, Lesson } from "../types";
function dev(
  id: string,
  name: string,
  kind: Kind,
  x: number,
  y: number,
  w: number,
  h: number,
  top: string[],
  bottom: string[] = [],
  role?: string,
  color?: string,
): Device {
  return {
    id,
    name,
    kind,
    x,
    y,
    w,
    h,
    role,
    color,
    terminals: [
      ...top.map((label, i) => ({
        id: `${id}.${label}`,
        label,
        x: ((i + 1) * w) / (top.length + 1),
        y: 0,
      })),
      ...bottom.map((label, i) => ({
        id: `${id}.${label}`,
        label,
        x: ((i + 1) * w) / (bottom.length + 1),
        y: h,
      })),
    ],
  };
}
