export function terminalInfo(lesson: Lesson, id: string) {
  for (const d of lesson.devices) {
    const t = d.terminals.find((t) => t.id === id);
    if (t) return { device: d, terminal: t, x: d.x + t.x, y: d.y + t.y };
  }
  return undefined;
}
export function terminalLabel(lesson: Lesson, id: string) {
  const t = terminalInfo(lesson, id);
  return t ? `${t.device.id} · ${t.terminal.label}` : id;
}
